import type { Folder, RecordItem } from '../types';

// ── Helper to create Tiptap JSON content ──
function doc(...content: Record<string, unknown>[]): Record<string, unknown> {
  return { type: 'doc', content };
}
function heading(level: number, text: string) {
  return { type: 'heading', attrs: { level }, content: [textNode(text)] };
}
function paragraph(text: string) {
  return { type: 'paragraph', content: [textNode(text)] };
}
function textNode(text: string) {
  return { type: 'text', text };
}
function bulletList(items: string[]) {
  return { type: 'bulletList', content: items.map(item => ({ type: 'listItem', content: [paragraph(item)] })) };
}
function orderedList(items: string[]) {
  return { type: 'orderedList', content: items.map(item => ({ type: 'listItem', content: [paragraph(item)] })) };
}
function taskList(items: { text: string; checked: boolean }[]) {
  return {
    type: 'taskList',
    content: items.map(item => ({
      type: 'taskItem',
      attrs: { checked: item.checked },
      content: [paragraph(item.text)],
    })),
  };
}
function hr() {
  return { type: 'horizontalRule' };
}
function blockquote(text: string) {
  return { type: 'blockquote', content: [paragraph(text)] };
}

